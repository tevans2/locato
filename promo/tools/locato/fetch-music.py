"""Download the default background tracks (Mixkit, Stock Music Free License), trim lead-in silence,
level their loudness and save them to public/locato/music/ with a LICENSES.md record.

    python3 tools/locato/fetch-music.py

To change a template's track: edit TRACKS (any https://assets.mixkit.co/music/<id>/<id>.mp3),
re-run, and update MUSIC in src/locato/brand.ts if you add a new name.
"""
import os
import subprocess
import tempfile
import urllib.request
import wave

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "public/locato/music")
TARGET_RMS_DB = -18.0  # every track lands at the same loudness; the mix sets the final level

# name -> (mixkit id, title, artist, used for)
TRACKS = {
    "gummies": (1142, "Gummies", "Michael Ramir C.", "quiz"),
    "placeit-world": (724, "PlaceIt World 01", "Lily J", "daily"),
    "close-up": (1167, "Close Up", "Michael Ramir C.", "look-alikes"),
    "running-out-of-time": (77, "Running Out of Time", "Ahjay Stelino", "speedrun"),
    "what-about-action": (474, "What About Action?", "Diego Nava", "versus"),
    "motivating-mornings": (33, "Motivating Mornings", "Ahjay Stelino", "leaderboard"),
}


def ffmpeg(*args):
    subprocess.run(["npx", "remotion", "ffmpeg", "-y", "-loglevel", "error", *args], check=True, cwd=ROOT)


os.makedirs(OUT, exist_ok=True)
rows = []
with tempfile.TemporaryDirectory() as tmp:  # downloads stay out of the project until processed
    for name, (mid, title, artist, use) in TRACKS.items():
        url = f"https://assets.mixkit.co/music/{mid}/{mid}.mp3"
        mp3 = os.path.join(tmp, f"{mid}.mp3")
        req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
        with urllib.request.urlopen(req) as r, open(mp3, "wb") as f:
            f.write(r.read())
        wav = os.path.join(tmp, f"{mid}.wav")
        ffmpeg("-i", mp3, "-ac", "2", "-ar", "48000", wav)
        with wave.open(wav) as w:
            x = np.frombuffer(w.readframes(w.getnframes()), "<i2").astype(float).reshape(-1, 2) / 32768
        mono = x.mean(1)
        # trim lead-in: start where the music first reaches -30 dB of its loudest 50ms
        hop = 2400
        env = np.sqrt(np.array([(mono[i:i + hop] ** 2).mean() for i in range(0, len(mono) - hop, hop)]) + 1e-12)
        start = int(np.argmax(env > env.max() * 10 ** (-30 / 20))) * hop
        x = x[start:]
        gain = 10 ** (TARGET_RMS_DB / 20) / np.sqrt((x ** 2).mean())
        x = x * gain
        peak = np.abs(x).max()
        if peak > 0.97:  # never clip: soft-limit by scaling down instead
            x *= 0.97 / peak
        fade = int(0.01 * 48000)
        x[:fade] *= np.linspace(0, 1, fade)[:, None]
        tmpwav = os.path.join(tmp, f"{name}.wav")
        with wave.open(tmpwav, "wb") as w:
            w.setnchannels(2)
            w.setsampwidth(2)
            w.setframerate(48000)
            w.writeframes((x * 32767).astype("<i2").tobytes())
        dest = os.path.join(OUT, f"{name}.m4a")
        ffmpeg("-i", tmpwav, "-c:a", "aac", "-b:a", "192k", "-f", "mp4", dest)
        rows.append(f"| `{name}.m4a` | {title} | {artist} | {use} | {url} |")
        print(f"{name:22} {title} ({artist}) trimmed {start / 48000:.2f}s, gain {20 * np.log10(gain):+.1f} dB -> {os.path.relpath(dest, ROOT)}")

with open(os.path.join(OUT, "LICENSES.md"), "w") as f:
    f.write(
        "# Background music\n\n"
        "All tracks are from [Mixkit](https://mixkit.co/free-stock-music/) under the "
        "[Mixkit Stock Music Free License](https://mixkit.co/license/#musicFree): free for personal and commercial "
        "projects, including social media and online advertising, with no attribution required. The license does not "
        "allow use in video games themselves, CDs/DVDs or TV/radio broadcast, so use these in promo videos only, "
        "not inside the Locato game.\n\n"
        "Files were trimmed of lead-in silence and loudness-levelled by `tools/locato/fetch-music.py`.\n\n"
        "| File | Track | Artist | Default for | Source |\n|---|---|---|---|---|\n" + "\n".join(rows) + "\n"
        "\n`bed.wav` is generated by `tools/locato/make-sounds.py` (no license needed).\n"
    )
print("wrote public/locato/music/LICENSES.md")
