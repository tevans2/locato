const legacyFrames = new Map(streetViewCountryRounds.map(({ countryCode, frames }) => [countryCode, frames]));

export const streetViewCatalog: readonly StreetViewCountryRound[] = [...new Set([...legacyFrames.keys(), ...Object.keys(extraLocations)])]
  .sort()
  .map((countryCode) => ({
    countryCode,
    frames: [
      ...(legacyFrames.get(countryCode) ?? []),
      ...(extraLocations[countryCode] ?? []).map(([lat, lng], index): StreetViewFrame => ({
        lat, lng, heading: (55 + 137 * index) % 360, label: "Street View",
      })),
    ],
  }));

export function streetViewLocationKey(frame: Pick<StreetViewFrame, "lat" | "lng">): string {
  return `${frame.lat.toFixed(4)},${frame.lng.toFixed(4)}`;
}

export function streetViewRoundId(round: StreetViewCountryRound): string {
  return round.frames.map(streetViewLocationKey).join("|");
}

export function streetViewRoundForReplay(countryCode: string, targetId?: string): StreetViewCountryRound | undefined {
  if (targetId === undefined) return streetViewCountryRounds.find((round) => round.countryCode === countryCode);
  const keys = targetId.split("|");
  if (keys.length !== 3 || new Set(keys).size !== 3) return undefined;
  const country = streetViewCatalog.find((round) => round.countryCode === countryCode);
  const frames = keys.map((key) => country?.frames.find((frame) => streetViewLocationKey(frame) === key));
  if (frames.every((frame) => frame !== undefined)) return { countryCode, frames };
}
