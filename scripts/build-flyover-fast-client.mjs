import { build } from "esbuild";
import { readFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
await build({
  absWorkingDir: root,
  entryPoints: ["scripts/flyover-fast-client-entry.ts"],
  outfile: "scripts/flyover-fast-client.js",
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "es2022",
  minify: false,
  legalComments: "none",
  loader: { ".css": "empty" },
  banner: { js: "/* Sign in, then paste this entire script on solo Flyover's Take off screen.\n * Fast physics: speed, turn rate and touch radius ×3; clock remains 90s.\n * Finished scores submit to your account's leaderboard through the normal API.\n * Restore the normal client with flyoverFastClient.restore() or reload.\n * Generated by: node scripts/build-flyover-fast-client.mjs\n */" },
  plugins: [{
    name: "isolated-fast-physics",
    setup(buildApi) {
      buildApi.onLoad({ filter: /src\/core\/flyover\/index\.ts$/ }, async ({ path }) => {
        let source = await readFile(path, "utf8");
        for (const [before, after] of [
          ["export const FLYOVER_SPEED = 42;", "export const FLYOVER_SPEED = 126;"],
          ["export const FLYOVER_TURN_RATE = Math.PI * 0.95;", "export const FLYOVER_TURN_RATE = Math.PI * 2.85;"],
          ["export const FLYOVER_TOUCH_RADIUS = 2.2;", "export const FLYOVER_TOUCH_RADIUS = 6.6;"],
        ]) {
          if (!source.includes(before)) throw new Error(`Physics source changed: ${before}`);
          source = source.replace(before, after);
        }
        return { contents: source, loader: "ts" };
      });
      buildApi.onLoad({ filter: /scripts\/flyover-autopilot\.js$/ }, async ({ path }) => {
        const source = await readFile(path, "utf8");
        const start = source.indexOf("(async () => {");
        const end = source.lastIndexOf("})();");
        if (start < 0 || end < start) throw new Error("Autopilot installer format changed.");
        return { contents: "export default async function installAutopilot() {" + source.slice(start + "(async () => {".length, end) + "}", loader: "js" };
      });
    },
  }],
});
console.log("Built scripts/flyover-fast-client.js with isolated fast physics.");
